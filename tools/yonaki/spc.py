"""SPC700 sound driver of 夜鳴き鐘 (original), assembled here.  Derived from the driver of 潮鳴りの密室
(tools/adv/spc.py) and extended: compact score bytecode with repeats / calls / bends, two effect slots
with multi-step effects (samples, the noise generator, slides, volume moves), a rain ambience made of
random droplets, per-song echo, fades on a fixed 100 Hz clock.  The CPU protocol: tools/yonaki/audio.py.

DSP voices: 0 = effect slot A, 1 = effect slot B and the ambience (while slot B is free),
2-7 = the six music channels.
Timer 0 ticks at 100 Hz (effects, ambience, fades); timer 1 is the music tempo (per song).
Every KON write is followed by a short wait (> 64 SPC700 cycles): the DSP reads KON every other sample.
Notes end by switching the voice from ADSR to an exponential GAIN decrease, never by KOF.
"""
import pathlib, struct, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import music

ORG = 0x0200
ECHO_PAGE, ECHO_EDL = 0xE0, 4    # echo buffer $E000-$FFFF (64 ms)
ECHO_FIR = (0x0C, 0x21, 0x2B, 0x2B, 0x13, 0xFE, 0xF3, 0xF9)
MASTER_VOL = 0x5C
DEFAULT_EFB, DEFAULT_EVOL = 0x48, 0x24
VIB_SPEED, VIB_DELAY = 14, 14
NCH = 6
DIR_SLOTS = 64

# ---------------------------------------------------------------- zero page
LAST, TMP, TMP2, CP, TL, VBASE, NT1, MUTED, SONG_ON, FADE, FADING, FTARGET, BEAT, TICKC, KONACC, SONGNO = (
    0x00, 0x01, 0x02, 0x03, 0x05, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11)
ECHOWAIT, RNDL, RNDH, FLGV, EONM, EONS, NONV, AMB, AMBCNT, AMBVOL, AMBTGT, RUML, RUMH, EVOLV, SLOT, TMP3 = (
    0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F, 0x20, 0x21)
CP2 = 0x22                       # 2 bytes
VSPEED = 0x38
# effect slots (X = 0 / 1)
S_PTRL, S_PTRH, S_T, S_ON, S_PL, S_PH, S_SLL, S_SLH, S_VL, S_VR = (0x24 + 2 * i for i in range(10))
# music channels (X = 0-5)
(ON, PTRL, PTRH, DUR, LEN, GATE, ADSR1, ADSR2, REL, VOLL, VOLR, PL, PH, VDEP, VAMP, VPH, VDLY, KEYED, TRANS,
 TUNE, BD, BN, BCNT, BSL, BSH, REPC) = (0x40 + NCH * i for i in range(26))
assert REPC + NCH <= 0xF0
# rarely used channel arrays (absolute,X)
REPL, REPH, RETL, RETH = (0x0100 + NCH * i for i in range(4))


class Asm:
    def __init__(self, org):
        self.org = org
        self.code = bytearray()
        self.labels = {}
        self.fix = []
        self.n = 0

    def here(self):
        return self.org + len(self.code)

    def label(self, name):
        assert name not in self.labels, name
        self.labels[name] = self.here()

    def uniq(self, p='L'):
        self.n += 1
        return f'_{p}{self.n}'

    def b(self, *v):
        self.code += bytes(v)

    def rel(self, op, label):
        self.b(op, 0)
        self.fix.append((len(self.code) - 1, label, 'rel'))

    def absop(self, op, label, add=0):
        self.b(op, 0, 0)
        self.fix.append((len(self.code) - 2, (label, add), 'abs'))

    def data(self, bs):
        self.code += bytes(bs)

    def word(self, label):
        self.b(0, 0)
        self.fix.append((len(self.code) - 2, (label, 0), 'abs'))

    # moves
    def mov_dp_imm(self, dp, v): self.b(0x8F, v & 0xFF, dp)
    def mov_dp_a(self, dp): self.b(0xC4, dp)
    def mov_a_dp(self, dp): self.b(0xE4, dp)
    def mov_a_imm(self, v): self.b(0xE8, v & 0xFF)
    def mov_x_imm(self, v): self.b(0xCD, v & 0xFF)
    def mov_y_imm(self, v): self.b(0x8D, v & 0xFF)
    def mov_x_a(self): self.b(0x5D)
    def mov_a_x(self): self.b(0x7D)
    def mov_y_a(self): self.b(0xFD)
    def mov_a_y(self): self.b(0xDD)
    def mov_x_dp(self, dp): self.b(0xF8, dp)
    def mov_dp_x(self, dp): self.b(0xD8, dp)
    def mov_y_dp(self, dp): self.b(0xEB, dp)
    def mov_dp_y(self, dp): self.b(0xCB, dp)
    def mov_a_ind_y(self, dp): self.b(0xF7, dp)
    def mov_ind_y_a(self, dp): self.b(0xD7, dp)
    def mov_a_dpx(self, dp): self.b(0xF4, dp)
    def mov_dpx_a(self, dp): self.b(0xD4, dp)
    def mov_y_dpx(self, dp): self.b(0xFB, dp)
    def mov_dpx_y(self, dp): self.b(0xDB, dp)
    def mov_a_absx(self, label, add=0):
        if isinstance(label, int):
            self.b(0xF5, label & 0xFF, label >> 8)
        else:
            self.absop(0xF5, label, add)
    def mov_absx_a(self, addr): self.b(0xD5, addr & 0xFF, addr >> 8)
    def mov_a_absy(self, label, add=0): self.absop(0xF6, label, add)
    def movw_ya_dp(self, dp): self.b(0xBA, dp)
    def movw_dp_ya(self, dp): self.b(0xDA, dp)
    # arithmetic
    def adc_a_imm(self, v): self.b(0x88, v & 0xFF)
    def adc_a_dp(self, dp): self.b(0x84, dp)
    def adc_a_dpx(self, dp): self.b(0x94, dp)
    def sbc_a_imm(self, v): self.b(0xA8, v & 0xFF)
    def sbc_a_dp(self, dp): self.b(0xA4, dp)
    def sbc_a_dpx(self, dp): self.b(0xB4, dp)
    def cmp_a_imm(self, v): self.b(0x68, v & 0xFF)
    def cmp_a_dp(self, dp): self.b(0x64, dp)
    def cmp_a_dpx(self, dp): self.b(0x74, dp)
    def cmp_x_imm(self, v): self.b(0xC8, v)
    def and_a_imm(self, v): self.b(0x28, v & 0xFF)
    def and_a_dp(self, dp): self.b(0x24, dp)
    def or_a_imm(self, v): self.b(0x08, v & 0xFF)
    def or_a_dp(self, dp): self.b(0x04, dp)
    def or_a_absx(self, label): self.absop(0x15, label)
    def eor_a_imm(self, v): self.b(0x48, v & 0xFF)
    def asl_a(self): self.b(0x1C)
    def lsr_a(self): self.b(0x5C)
    def lsr_dp(self, dp): self.b(0x4B, dp)
    def ror_dp(self, dp): self.b(0x6B, dp)
    def inc_dp(self, dp): self.b(0xAB, dp)
    def dec_dp(self, dp): self.b(0x8B, dp)
    def inc_dpx(self, dp): self.b(0xBB, dp)
    def dec_dpx(self, dp): self.b(0x9B, dp)
    def inc_x(self): self.b(0x3D)
    def inc_y(self): self.b(0xFC)
    def dec_y(self): self.b(0xDC)
    def mul(self): self.b(0xCF)
    def xcn(self): self.b(0x9F)
    def addw(self, dp): self.b(0x7A, dp)
    def subw(self, dp): self.b(0x9A, dp)
    def push_a(self): self.b(0x2D)
    def pop_a(self): self.b(0xAE)
    def push_x(self): self.b(0x4D)
    def pop_x(self): self.b(0xCE)
    def push_y(self): self.b(0x6D)
    def pop_y(self): self.b(0xEE)
    def clrc(self): self.b(0x60)
    def setc(self): self.b(0x80)
    # flow
    def bpl(self, l): self.rel(0x10, l)
    def bmi(self, l): self.rel(0x30, l)
    def bcc(self, l): self.rel(0x90, l)
    def bcs(self, l): self.rel(0xB0, l)
    def beq(self, l): self.rel(0xF0, l)
    def bne(self, l): self.rel(0xD0, l)
    def bra(self, l): self.rel(0x2F, l)
    def dbnz_y(self, l): self.rel(0xFE, l)
    def call(self, l): self.absop(0x3F, l)
    def jmp(self, l): self.absop(0x5F, l)
    def ret(self): self.b(0x6F)

    def beq_far(self, l):
        self.b(0xD0, 3)
        self.jmp(l)

    def bne_far(self, l):
        self.b(0xF0, 3)
        self.jmp(l)

    def bcc_far(self, l):
        self.b(0xB0, 3)
        self.jmp(l)

    def bcs_far(self, l):
        self.b(0x90, 3)
        self.jmp(l)

    def dsp(self, reg, v):
        self.mov_dp_imm(0xF2, reg)
        self.mov_dp_imm(0xF3, v)

    def dsp_a(self, reg):
        self.mov_dp_imm(0xF2, reg)
        self.mov_dp_a(0xF3)

    def dsp_v(self, reg):
        """DSP register VBASE | reg <- A (keeps A)."""
        self.push_a()
        self.mov_a_dp(VBASE)
        self.or_a_imm(reg)
        self.mov_dp_a(0xF2)
        self.pop_a()
        self.mov_dp_a(0xF3)

    def link(self):
        for off, target, kind in self.fix:
            if kind == 'rel':
                d = self.labels[target] - (self.org + off + 1)
                assert -128 <= d <= 127, (target, d)
                self.code[off] = d & 0xFF
            else:
                lab, add = target
                a = self.labels[lab] + add
                self.code[off:off + 2] = struct.pack('<H', a)
        return bytes(self.code)


def assemble(n_songs, n_sfx, n_amb, amb_tables):
    """The driver code and its fixed tables; data tables (DIR, instruments, songs, effects) are linked
    by label: 'insttab', 'songptr', 'sfxptr', 'ptl', 'pth', plus the DIR page patched by the caller."""
    a = Asm(ORG)
    a.label('start')
    a.mov_x_imm(0xFF)
    a.b(0xBD)                            # MOV SP,X
    a.mov_dp_imm(0xF1, 0x00)
    a.mov_dp_imm(0xFA, 80)               # T0: 100 Hz
    a.mov_dp_imm(0xFB, 125)
    a.dsp(0x6C, 0x60)                    # FLG: mute, echo writes off
    a.dsp(0x5C, 0xFF)                    # KOF all
    for r in (0x0C, 0x1C, 0x2C, 0x3C):
        a.dsp(r, 0)
    a.dsp(0x6D, ECHO_PAGE)
    a.dsp(0x7D, ECHO_EDL)
    a.dsp(0x0D, 0)
    for i, c in enumerate(ECHO_FIR):
        a.dsp(0x0F + 0x10 * i, c)
    a.dsp(0x4D, 0)
    a.dsp(0x3D, 0)
    a.dsp(0x2D, 0)
    a.dsp(0x5D, 0)
    a.label('dir_imm')                   # the DIR page is patched at offset dir_imm - 1
    for v in range(8):
        a.dsp(v << 4 | 0, 0)
        a.dsp(v << 4 | 1, 0)
        a.dsp(v << 4 | 4, 0)
        a.dsp(v << 4 | 5, 0)
        a.dsp(v << 4 | 7, 0)
    # clear the zero page ($00-$EF) and the page-1 arrays
    a.mov_x_imm(0)
    a.label('zclr')
    a.mov_a_imm(0)
    a.b(0xAF)                            # MOV (X)+,A
    a.cmp_x_imm(0xF0)
    a.bne('zclr')
    a.mov_x_imm(0)
    a.label('pclr')
    a.mov_a_imm(0)
    a.mov_absx_a(0x0100)
    a.inc_x()
    a.cmp_x_imm(0x40)
    a.bne('pclr')
    # clear the echo buffer
    a.mov_dp_imm(CP, 0)
    a.mov_dp_imm(CP + 1, ECHO_PAGE)
    a.mov_y_imm(0)
    a.label('eclr')
    a.mov_a_imm(0)
    a.mov_ind_y_a(CP)
    a.inc_y()
    a.bne('eclr')
    a.inc_dp(CP + 1)
    a.bne('eclr')                        # up to $FFFF (the page wraps to 0)
    a.mov_dp_imm(FLGV, 0x20)
    a.dsp(0x6C, 0x20)                    # not muted, echo writes still off
    a.dsp(0x0C, MASTER_VOL)
    a.dsp(0x1C, MASTER_VOL)
    a.dsp(0x5C, 0x00)
    a.mov_dp_imm(EVOLV, DEFAULT_EVOL)
    a.dsp(0x0D, DEFAULT_EFB)
    a.dsp(0x2C, DEFAULT_EVOL)
    a.dsp(0x3C, DEFAULT_EVOL)
    a.mov_dp_imm(ECHOWAIT, 30)
    a.mov_dp_imm(FADE, 0xFF)
    a.mov_dp_imm(FTARGET, 0xFF)
    a.mov_dp_imm(RNDL, 0xE1)
    a.mov_dp_imm(RNDH, 0xAC)
    a.mov_a_dp(0xF5)
    a.mov_dp_a(LAST)
    a.mov_dp_imm(0xF6, 0)
    a.mov_dp_imm(0xF7, 0)
    a.mov_dp_imm(0xF1, 0x03)
    a.mov_a_dp(0xFE)
    a.mov_a_dp(0xFD)
    a.mov_dp_imm(0xF4, 0x5A)             # ready
    a.label('loop')
    a.mov_a_dp(0xFD)
    a.beq('noclk')
    a.call('tick')
    a.label('noclk')
    a.mov_a_dp(0xFE)
    a.beq('nomusic')
    a.mov_dp_a(NT1)
    a.label('mt')
    a.call('mtick')
    a.dec_dp(NT1)
    a.bne('mt')
    a.label('nomusic')
    a.mov_a_dp(0xF5)
    a.cmp_a_dp(LAST)
    a.beq('loop')
    a.mov_dp_a(LAST)
    a.mov_a_dp(0xF4)
    a.call('command')
    a.bra('loop')

    # ------------------------------------------------------------ commands
    a.label('command')
    for v, lab in ((0x30, 'mute'), (0x31, 'unmute'), (0x60, 'mfade'), (0x61, 'mstop'), (0x62, 'mduck'),
                   (0x63, 'munduck'), (0x64, 'sfxstop'), (0x7F, 'ambstop')):
        a.cmp_a_imm(v)
        a.beq_far(lab)
    a.cmp_a_imm(0x70)
    a.bcc('c_notamb')
    a.cmp_a_imm(0x70 + n_amb)
    a.bcs('c_ret')
    a.jmp('ambstart')
    a.label('c_notamb')
    a.cmp_a_imm(0x40)
    a.bcc('c_notsong')
    a.cmp_a_imm(0x40 + n_songs)
    a.bcs('c_ret')
    a.jmp('song')
    a.label('c_notsong')
    a.cmp_a_imm(0)
    a.beq('c_ret')
    a.cmp_a_imm(n_sfx + 1)
    a.bcs('c_ret')
    a.jmp('sfx')
    a.label('c_ret')
    a.ret()

    a.label('mute')
    a.mov_dp_imm(MUTED, 1)
    for r in (0x0C, 0x1C, 0x2C, 0x3C):
        a.dsp(r, 0)
    a.ret()
    a.label('unmute')
    a.mov_dp_imm(MUTED, 0)
    a.dsp(0x0C, MASTER_VOL)
    a.dsp(0x1C, MASTER_VOL)
    a.label('setevol')
    a.mov_a_dp(MUTED)
    a.bne('sev_ret')
    a.mov_a_dp(EVOLV)
    a.dsp_a(0x2C)
    a.dsp_a(0x3C)
    a.label('sev_ret')
    a.ret()

    # A = key-on bits; then wait > 64 cycles
    a.label('kon')
    a.dsp_a(0x4C)
    a.mov_y_imm(24)
    a.label('konwait')
    a.dbnz_y('konwait')
    a.ret()

    a.label('seteon')
    a.mov_a_dp(EONM)
    a.or_a_dp(EONS)
    a.dsp_a(0x4D)
    a.ret()

    # ------------------------------------------------------------ 100 Hz tick
    a.label('tick')
    a.mov_a_dp(ECHOWAIT)
    a.beq('t_echo')
    a.dec_dp(ECHOWAIT)
    a.bne('t_echo')
    a.mov_dp_imm(FLGV, 0)
    a.mov_a_dp(FLGV)
    a.dsp_a(0x6C)                        # echo writes on
    a.label('t_echo')
    a.mov_x_imm(0)
    a.call('slot_tick')
    a.mov_x_imm(1)
    a.call('slot_tick')
    a.call('amb_tick')
    a.jmp('fade_tick')

    # ------------------------------------------------------------ effects
    # A = effect number (1..)
    a.label('sfx')
    a.mov_dp_a(TMP3)
    a.mov_a_dp(MUTED)
    a.beq('sfx_go')
    a.ret()
    a.label('sfx_go')
    a.mov_x_imm(0)                       # slot: A if free, else B if free, else A
    a.mov_a_dpx(S_ON)
    a.beq('sfx_slot')
    a.mov_x_imm(1)
    a.mov_a_dpx(S_ON)
    a.beq('sfx_slot')
    a.mov_x_imm(0)
    a.label('sfx_slot')
    a.mov_a_dp(TMP3)
    a.call('sfx_begin')
    # companion effect on the other slot
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP2)
    a.beq('sfx_ret')
    a.push_a()
    a.mov_a_x()
    a.eor_a_imm(1)
    a.mov_x_a()
    a.pop_a()
    a.call('sfx_begin')
    a.label('sfx_ret')
    a.ret()

    # X = slot, A = effect number: CP2 = header; the slot starts with its first step
    a.label('sfx_begin')
    a.asl_a()
    a.mov_y_a()
    a.mov_a_absy('sfxptr', -2)
    a.mov_dp_a(CP2)
    a.mov_a_absy('sfxptr', -1)
    a.mov_dp_a(CP2 + 1)
    a.mov_a_dp(CP2)
    a.clrc()
    a.adc_a_imm(2)
    a.mov_dpx_a(S_PTRL)
    a.mov_a_dp(CP2 + 1)
    a.adc_a_imm(0)
    a.mov_dpx_a(S_PTRH)
    a.mov_a_imm(1)
    a.mov_dpx_a(S_ON)
    a.mov_a_imm(0)
    a.mov_dpx_a(S_SLL)
    a.mov_dpx_a(S_SLH)
    # echo bit of this voice from the header flags (bit 0)
    a.mov_a_absx('vbit')
    a.eor_a_imm(0xFF)
    a.and_a_dp(EONS)
    a.mov_dp_a(EONS)
    a.mov_y_imm(0)
    a.mov_a_ind_y(CP2)
    a.and_a_imm(1)
    a.beq('sb_dry')
    a.mov_a_absx('vbit')
    a.or_a_dp(EONS)
    a.mov_dp_a(EONS)
    a.label('sb_dry')
    a.call('seteon')
    a.push_x()
    a.call('sfx_step')
    a.pop_x()
    a.ret()

    # X = slot: run steps until one that waits
    a.label('sfx_step')
    a.mov_a_x()
    a.xcn()
    a.mov_dp_a(VBASE)
    a.label('ss_again')
    a.mov_a_dpx(S_PTRL)
    a.mov_dp_a(CP)
    a.mov_a_dpx(S_PTRH)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.mov_a_ind_y(CP)
    a.cmp_a_imm(0xFF)
    a.bne('ss_1')
    # end: release (fast exponential), the slot is free
    a.mov_a_imm(0)
    a.dsp_v(0x05)
    a.mov_a_imm(0xA0 | 24)
    a.dsp_v(0x07)
    a.mov_a_imm(0)
    a.mov_dpx_a(S_ON)
    a.mov_dpx_a(S_T)
    a.mov_a_absx('vbit')
    a.eor_a_imm(0xFF)
    a.push_a()
    a.and_a_dp(NONV)
    a.mov_dp_a(NONV)
    a.dsp_a(0x3D)
    a.pop_a()
    a.and_a_dp(EONS)
    a.mov_dp_a(EONS)
    a.jmp('seteon')
    a.label('ss_1')
    a.cmp_a_imm(0xFE)                    # release: $FE gain ticks
    a.bne('ss_2')
    a.mov_a_imm(0)
    a.dsp_v(0x05)
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.dsp_v(0x07)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_T)
    a.mov_a_imm(3)
    a.jmp('ss_adv')
    a.label('ss_2')
    a.cmp_a_imm(0xFD)                    # volume: $FD l r ticks
    a.bne('ss_3')
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_VL)
    a.call('svol_l')
    a.mov_y_imm(2)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_VR)
    a.call('svol_r')
    a.mov_y_imm(3)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_T)
    a.mov_a_imm(4)
    a.jmp('ss_adv')
    a.label('ss_3')
    a.cmp_a_imm(0xFC)                    # slide: $FC lo hi (no wait)
    a.bne('ss_4')
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_SLL)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_SLH)
    a.mov_a_imm(3)
    a.call('ss_advp')
    a.jmp('ss_again')
    a.label('ss_4')
    a.cmp_a_imm(0xFB)                    # pitch: $FB lo hi (no wait, no key-on)
    a.bne('ss_5')
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PL)
    a.dsp_v(0x02)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PH)
    a.dsp_v(0x03)
    a.mov_a_imm(3)
    a.call('ss_advp')
    a.jmp('ss_again')
    a.label('ss_5')
    a.cmp_a_imm(0xF9)                    # jump: $F9 lo hi
    a.bne('ss_6')
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PTRL)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PTRH)
    a.jmp('ss_again')
    a.label('ss_6')
    # key on: src (bit 7: noise, clock = bits 0-4), pl, ph, vl, vr, adsr1, adsr2/gain, ticks
    a.mov_dp_a(TMP)
    a.and_a_imm(0x80)
    a.beq('ss_smp')
    a.mov_a_absx('vbit')
    a.or_a_dp(NONV)
    a.mov_dp_a(NONV)
    a.mov_a_dp(TMP)
    a.and_a_imm(0x1F)
    a.mov_dp_a(TMP2)
    a.mov_a_dp(FLGV)
    a.and_a_imm(0xE0)
    a.or_a_dp(TMP2)
    a.mov_dp_a(FLGV)
    a.dsp_a(0x6C)
    a.bra('ss_src')
    a.label('ss_smp')
    a.mov_a_absx('vbit')
    a.eor_a_imm(0xFF)
    a.and_a_dp(NONV)
    a.mov_dp_a(NONV)
    a.mov_a_dp(TMP)
    a.dsp_v(0x04)
    a.label('ss_src')
    a.mov_a_dp(NONV)
    a.dsp_a(0x3D)
    a.mov_y_imm(1)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PL)
    a.dsp_v(0x02)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_PH)
    a.dsp_v(0x03)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_VL)
    a.call('svol_l')
    a.mov_y_imm(4)
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_VR)
    a.call('svol_r')
    a.mov_y_imm(5)
    a.mov_a_ind_y(CP)
    a.dsp_v(0x05)
    a.mov_dp_a(TMP)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.dsp_v(0x06)
    a.dsp_v(0x07)                        # (GAIN too: used when ADSR1 bit 7 is clear)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(S_T)
    a.mov_a_absx('vbit')
    a.call('kon')
    a.mov_a_imm(8)
    a.label('ss_adv')
    a.call('ss_advp')
    a.ret()
    a.label('ss_advp')                   # S_PTR += A
    a.clrc()
    a.adc_a_dpx(S_PTRL)
    a.mov_dpx_a(S_PTRL)
    a.mov_a_imm(0)
    a.adc_a_dpx(S_PTRH)
    a.mov_dpx_a(S_PTRH)
    a.ret()
    # effect volume (A) -> DSP, scaled by nothing (master volume handles mute)
    a.label('svol_l')
    a.dsp_v(0x00)
    a.ret()
    a.label('svol_r')
    a.dsp_v(0x01)
    a.ret()

    # X = slot: slide, count down
    a.label('slot_tick')
    a.mov_a_dpx(S_ON)
    a.bne('st_on')
    a.ret()
    a.label('st_on')
    a.mov_a_x()
    a.xcn()
    a.mov_dp_a(VBASE)
    a.mov_a_dpx(S_SLL)
    a.mov_dp_a(TMP)
    a.mov_a_dpx(S_SLH)
    a.or_a_dp(TMP)
    a.beq('st_count')
    a.mov_a_dpx(S_PL)
    a.clrc()
    a.adc_a_dpx(S_SLL)
    a.mov_dpx_a(S_PL)
    a.dsp_v(0x02)
    a.mov_a_dpx(S_PH)
    a.adc_a_dpx(S_SLH)
    a.and_a_imm(0x3F)
    a.mov_dpx_a(S_PH)
    a.dsp_v(0x03)
    a.label('st_count')
    a.dec_dpx(S_T)
    a.bne('st_ret')
    a.jmp('sfx_step')
    a.label('st_ret')
    a.ret()

    a.label('sfxstop')
    a.mov_x_imm(0)
    a.label('sfs_l')
    a.mov_a_dpx(S_ON)
    a.beq('sfs_n')
    a.mov_a_imm(1)
    a.mov_dpx_a(S_T)
    a.mov_a_imm(0)
    a.mov_dpx_a(S_SLL)
    a.mov_dpx_a(S_SLH)
    a.push_x()
    a.mov_a_x()
    a.xcn()
    a.mov_dp_a(VBASE)
    a.mov_a_imm(0)
    a.dsp_v(0x05)
    a.mov_a_imm(0xA0 | 26)
    a.dsp_v(0x07)
    a.pop_x()
    a.mov_a_imm(0)
    a.mov_dpx_a(S_ON)
    a.label('sfs_n')
    a.inc_x()
    a.cmp_x_imm(2)
    a.bne('sfs_l')
    a.mov_dp_imm(EONS, 0)
    a.mov_dp_imm(NONV, 0)
    a.dsp(0x3D, 0)
    a.jmp('seteon')

    # ------------------------------------------------------------ ambience
    # random: 16-bit Galois LFSR, A = new low byte
    a.label('rnd')
    a.lsr_dp(RNDH)
    a.ror_dp(RNDL)
    a.bcc('rnd_ret')
    a.mov_a_dp(RNDH)
    a.eor_a_imm(0xB4)
    a.mov_dp_a(RNDH)
    a.label('rnd_ret')
    a.mov_a_dp(RNDL)
    a.ret()
    a.label('rnd8')                      # eight steps: a fresh byte
    a.push_x()
    a.mov_x_imm(8)
    a.label('rnd8l')
    a.call('rnd')
    a.b(0x1D)                            # DEC X
    a.bne('rnd8l')
    a.pop_x()
    a.mov_a_dp(RNDL)
    a.ret()

    a.label('ambstart')                  # A = $70 + k
    a.and_a_imm(0x0F)
    a.mov_x_a()
    a.mov_a_absx('amb_level')
    a.mov_dp_a(AMBTGT)
    a.mov_a_x()
    a.clrc()
    a.adc_a_imm(1)
    a.mov_dp_a(AMB)
    a.mov_dp_imm(AMBCNT, 1)
    a.mov_dp_imm(RUML, 0x00)
    a.mov_dp_imm(RUMH, 0x02)             # first rumble after ~5 s
    a.ret()
    a.label('ambstop')
    a.mov_dp_imm(AMBTGT, 0)
    a.ret()

    a.label('amb_tick')
    a.mov_a_dp(AMB)
    a.bne('am_on')
    a.ret()
    a.label('am_on')
    a.mov_a_dp(AMBVOL)                   # fade toward the target, 1 a tick (0.3-0.4 s at the rain levels)
    a.cmp_a_dp(AMBTGT)
    a.beq('am_lvl')
    a.bcs('am_down')
    a.clrc()
    a.adc_a_imm(1)
    a.cmp_a_dp(AMBTGT)
    a.bcc('am_set')
    a.mov_a_dp(AMBTGT)
    a.bra('am_set')
    a.label('am_down')
    a.setc()
    a.sbc_a_imm(1)
    a.bcc('am_zero')
    a.cmp_a_dp(AMBTGT)
    a.bcs('am_set')
    a.label('am_zero')
    a.mov_a_dp(AMBTGT)
    a.label('am_set')
    a.mov_dp_a(AMBVOL)
    a.label('am_lvl')
    a.mov_a_dp(AMBVOL)
    a.bne('am_play')
    a.mov_a_dp(AMBTGT)
    a.bne('am_ret')
    a.mov_dp_imm(AMB, 0)                 # faded out: off
    a.mov_x_imm(1)
    a.mov_a_dpx(S_ON)
    a.bne('am_ret')
    a.mov_dp_imm(VBASE, 0x10)
    a.mov_a_imm(0)
    a.dsp_v(0x05)
    a.mov_a_imm(0xA0 | 26)
    a.dsp_v(0x07)
    a.label('am_ret')
    a.ret()
    a.label('am_play')
    # storm: a distant rumble on slot A now and then
    a.mov_a_dp(AMB)
    a.cmp_a_imm(2)
    a.bne('am_drop')
    a.mov_a_dp(RUML)
    a.setc()
    a.sbc_a_imm(1)
    a.mov_dp_a(RUML)
    a.mov_a_dp(RUMH)
    a.sbc_a_imm(0)
    a.mov_dp_a(RUMH)
    a.bcs('am_drop')
    a.call('rnd8')                       # next one in 6-16 s
    a.and_a_imm(0x03)
    a.clrc()
    a.adc_a_imm(2)
    a.mov_dp_a(RUMH)
    a.call('rnd8')
    a.mov_dp_a(RUML)
    a.mov_x_imm(0)
    a.mov_a_dpx(S_ON)
    a.bne('am_drop')
    a.mov_a_dp(MUTED)
    a.bne('am_drop')
    a.mov_a_imm(amb_tables['rumble_sfx'])
    a.call('sfx_begin')
    a.label('am_drop')
    a.mov_x_imm(1)
    a.mov_a_dpx(S_ON)
    a.bne('am_ret')
    a.dec_dp(AMBCNT)
    a.bne('am_ret')
    # one droplet on voice 1
    a.mov_dp_imm(VBASE, 0x10)
    a.call('rnd8')
    a.and_a_imm(0x0F)
    a.mov_x_a()
    a.mov_a_absx('amb_gap')
    a.mov_dp_a(AMBCNT)
    a.call('rnd8')
    a.mov_dp_a(TMP3)
    a.and_a_imm(0x07)
    a.mov_x_a()
    a.mov_a_absx('amb_src')
    a.dsp_v(0x04)
    a.mov_a_dp(TMP3)
    a.lsr_a()
    a.lsr_a()
    a.lsr_a()
    a.and_a_imm(0x0F)
    a.asl_a()
    a.mov_x_a()
    a.mov_a_absx('amb_pitch')
    a.dsp_v(0x02)
    a.mov_a_absx('amb_pitch', 1)
    a.dsp_v(0x03)
    a.call('rnd8')                       # loudness and pan
    a.mov_dp_a(TMP3)
    a.and_a_imm(0x0F)
    a.mov_x_a()
    a.mov_a_absx('amb_vol')
    a.mov_y_a()
    a.mov_a_dp(AMBVOL)
    a.mul()
    a.mov_dp_y(TMP)                      # TMP = level
    a.mov_a_dp(TMP3)
    a.lsr_a()
    a.lsr_a()
    a.lsr_a()
    a.lsr_a()
    a.mov_x_a()
    a.mov_a_absx('amb_pan')              # 128..255 for the far side
    a.mov_y_a()
    a.mov_a_dp(TMP)
    a.mul()
    a.mov_dp_y(TMP2)                     # TMP2 = far side
    a.mov_a_dp(TMP3)
    a.bmi('am_r')
    a.mov_a_dp(TMP)
    a.dsp_v(0x00)
    a.mov_a_dp(TMP2)
    a.dsp_v(0x01)
    a.bra('am_k')
    a.label('am_r')
    a.mov_a_dp(TMP2)
    a.dsp_v(0x00)
    a.mov_a_dp(TMP)
    a.dsp_v(0x01)
    a.label('am_k')
    a.mov_a_imm(0)
    a.dsp_v(0x05)                        # GAIN: direct, full
    a.mov_a_imm(0x7F)
    a.dsp_v(0x07)
    a.mov_a_dp(NONV)
    a.and_a_imm(0xFD)
    a.mov_dp_a(NONV)
    a.dsp_a(0x3D)
    a.mov_a_dp(EONS)
    a.and_a_imm(0xFD)
    a.mov_dp_a(EONS)
    a.call('seteon')
    a.mov_a_imm(0x02)
    a.jmp('kon')

    # ------------------------------------------------------------ fades (100 Hz)
    a.label('fade_tick')
    a.mov_a_dp(SONG_ON)
    a.bne('ft_on')
    a.ret()
    a.label('ft_on')
    a.mov_a_dp(FADING)
    a.beq('ft_duck')
    a.mov_a_dp(FADE)
    a.setc()
    a.sbc_a_imm(3)
    a.bcs('ft_store')
    a.mov_dp_imm(FADE, 0)
    a.call('allvol')
    a.jmp('mstop')
    a.label('ft_duck')                   # toward the duck target: down 8 a tick, up 3
    a.mov_a_dp(FADE)
    a.cmp_a_dp(FTARGET)
    a.beq('ft_ret')
    a.bcc('ft_up')
    a.setc()
    a.sbc_a_imm(8)
    a.bcc('ft_clamp')
    a.cmp_a_dp(FTARGET)
    a.bcs('ft_store')
    a.label('ft_clamp')
    a.mov_a_dp(FTARGET)
    a.bra('ft_store')
    a.label('ft_up')
    a.clrc()
    a.adc_a_imm(3)
    a.bcs('ft_clamp')
    a.cmp_a_dp(FTARGET)
    a.bcs('ft_clamp')
    a.label('ft_store')
    a.mov_dp_a(FADE)
    a.jmp('allvol')
    a.label('ft_ret')
    a.ret()

    a.label('allvol')
    a.mov_x_imm(0)
    a.label('av_l')
    a.call('setvol')
    a.inc_x()
    a.cmp_x_imm(NCH)
    a.bne('av_l')
    a.ret()

    # ------------------------------------------------------------ music
    a.label('song')                      # A = $40 + n
    a.clrc()
    a.adc_a_imm(0xC0)
    a.mov_dp_a(SONGNO)
    a.call('msilence')
    a.mov_a_dp(SONGNO)
    a.asl_a()
    a.mov_x_a()
    a.mov_a_absx('songptr')
    a.mov_dp_a(CP)
    a.mov_a_absx('songptr', 1)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.mov_a_ind_y(CP)
    a.mov_dp_a(0xFB)                     # tempo
    a.mov_dp_imm(0xF1, 0x01)
    a.mov_dp_imm(0xF1, 0x03)
    a.mov_a_dp(0xFE)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.dsp_a(0x0D)                        # echo feedback
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dp_a(EVOLV)
    a.call('setevol')
    a.mov_y_imm(3)
    a.mov_a_ind_y(CP)
    a.mov_dp_a(EONM)
    a.call('seteon')
    a.mov_y_imm(4)
    a.mov_a_ind_y(CP)
    a.mov_dp_a(VSPEED)
    a.mov_y_imm(5)
    a.mov_x_imm(0)
    a.label('sch')
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(PTRL)
    a.mov_dp_a(TMP)
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dpx_a(PTRH)
    a.inc_y()
    a.or_a_dp(TMP)
    a.beq('sch0')
    a.mov_a_imm(1)
    a.label('sch0')
    a.mov_dpx_a(ON)
    a.mov_a_imm(1)
    a.mov_dpx_a(DUR)
    a.mov_dpx_a(LEN)
    a.mov_a_imm(0)
    for arr in (GATE, VDEP, VAMP, KEYED, VOLL, VOLR, BD, BN, BCNT, REPC):
        a.mov_dpx_a(arr)
    a.inc_x()
    a.cmp_x_imm(NCH)
    a.bne('sch')
    a.mov_a_dp(FTARGET)
    a.mov_dp_a(FADE)
    a.mov_dp_imm(FADING, 0)
    a.mov_dp_imm(BEAT, 0)
    a.mov_dp_imm(TICKC, 0)
    a.mov_dp_imm(0xF7, 0)
    a.mov_a_dp(SONGNO)
    a.clrc()
    a.adc_a_imm(1)
    a.mov_dp_a(0xF6)
    a.mov_dp_imm(SONG_ON, 1)
    a.ret()

    a.label('mfade')
    a.mov_dp_imm(FADING, 1)
    a.ret()
    a.label('mduck')
    a.mov_dp_imm(FTARGET, 0x60)
    a.ret()
    a.label('munduck')
    a.mov_dp_imm(FTARGET, 0xFF)
    a.ret()
    a.label('mstop')
    a.call('msilence')
    a.mov_dp_imm(SONG_ON, 0)
    a.mov_dp_imm(0xF6, 0)
    a.ret()

    a.label('msilence')                  # every channel off, a fast release (-40 dB in ~0.2 s)
    a.mov_x_imm(0)
    a.label('msl')
    a.call('vbase')
    a.mov_a_imm(0)
    a.mov_dpx_a(KEYED)
    a.dsp_v(0x05)
    a.mov_a_imm(0xA0 | 26)
    a.dsp_v(0x07)
    a.mov_a_imm(0)
    a.mov_dpx_a(ON)
    a.inc_x()
    a.cmp_x_imm(NCH)
    a.bne('msl')
    a.ret()

    a.label('vbase')
    a.mov_a_x()
    a.clrc()
    a.adc_a_imm(2)
    a.xcn()
    a.mov_dp_a(VBASE)
    a.ret()

    a.label('release')                   # channel X: exponential GAIN decrease
    a.mov_a_dpx(KEYED)
    a.beq('rel_ret')
    a.mov_a_imm(0)
    a.mov_dpx_a(KEYED)
    a.mov_a_dpx(REL)
    a.dsp_v(0x07)
    a.mov_a_dpx(ADSR1)
    a.and_a_imm(0x7F)
    a.dsp_v(0x05)
    a.label('rel_ret')
    a.ret()

    a.label('setvol')                    # channel X volume * FADE / 256 (clobbers Y)
    a.call('vbase')
    a.mov_y_dpx(VOLL)
    a.mov_a_dp(FADE)
    a.mul()
    a.mov_a_y()
    a.dsp_v(0x00)
    a.mov_y_dpx(VOLR)
    a.mov_a_dp(FADE)
    a.mul()
    a.mov_a_y()
    a.dsp_v(0x01)
    a.ret()

    a.label('mtick')
    a.mov_a_dp(SONG_ON)
    a.bne('mt_go')
    a.ret()
    a.label('mt_go')
    a.inc_dp(TICKC)
    a.mov_a_dp(TICKC)
    a.cmp_a_imm(music.TPQ)
    a.bne('mt_nobeat')
    a.mov_dp_imm(TICKC, 0)
    a.inc_dp(BEAT)
    a.mov_a_dp(BEAT)
    a.mov_dp_a(0xF7)
    a.label('mt_nobeat')
    a.mov_dp_imm(KONACC, 0)
    a.mov_dp_imm(TMP3, 0)                # channels still running
    a.mov_x_imm(0)
    a.label('mt_ch')
    a.mov_a_dpx(ON)
    a.beq('mt_next')
    a.call('channel')
    a.mov_a_dpx(ON)
    a.or_a_dp(TMP3)
    a.mov_dp_a(TMP3)
    a.label('mt_next')
    a.inc_x()
    a.cmp_x_imm(NCH)
    a.bne('mt_ch')
    a.mov_a_dp(KONACC)
    a.beq('mt_nk')
    a.call('kon')
    a.label('mt_nk')
    a.mov_a_dp(TMP3)
    a.bne('mt_ret')
    a.mov_dp_imm(SONG_ON, 0)             # every channel ended (a song that does not loop)
    a.mov_dp_imm(0xF6, 0)
    a.label('mt_ret')
    a.ret()

    # channel X: count down, fetch, gate, bend, vibrato
    a.label('channel')
    a.call('vbase')
    a.dec_dpx(DUR)
    a.bne('ch_run')
    a.jmp('fetch')
    a.label('ch_run')
    a.mov_a_dpx(DUR)
    a.cmp_a_dpx(GATE)
    a.bne('ch_pitch')
    # a tie next (possibly after a length byte)?  then no release
    a.mov_a_dpx(PTRL)
    a.mov_dp_a(CP)
    a.mov_a_dpx(PTRH)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.mov_a_ind_y(CP)
    a.beq('ch_rel')
    a.bpl('ch_peek')
    a.cmp_a_imm(0xE0)                    # a long length byte
    a.bne('ch_tie')
    a.inc_y()
    a.label('ch_peek')
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.label('ch_tie')
    a.cmp_a_imm(0xDC)
    a.beq('ch_pitch')
    a.label('ch_rel')
    a.call('release')
    a.label('ch_pitch')
    a.mov_dp_imm(TMP2, 0)
    a.mov_a_dpx(BCNT)
    a.beq('ch_vib')
    a.dec_dpx(BCNT)
    a.mov_a_dpx(PL)
    a.clrc()
    a.adc_a_dpx(BSL)
    a.mov_dpx_a(PL)
    a.mov_a_dpx(PH)
    a.adc_a_dpx(BSH)
    a.and_a_imm(0x3F)
    a.mov_dpx_a(PH)
    a.mov_dp_imm(TMP2, 1)
    a.label('ch_vib')
    a.mov_a_dpx(VAMP)
    a.beq('ch_novib')
    a.mov_a_dpx(KEYED)
    a.beq('ch_novib')
    a.mov_a_dpx(VDLY)
    a.beq('ch_dov')
    a.dec_dpx(VDLY)
    a.label('ch_novib')
    a.mov_a_dp(TMP2)
    a.bne('ch_wp')
    a.ret()
    a.label('ch_wp')
    a.mov_a_dpx(PL)
    a.dsp_v(0x02)
    a.mov_a_dpx(PH)
    a.dsp_v(0x03)
    a.ret()
    a.label('ch_dov')
    a.mov_a_dpx(VPH)
    a.clrc()
    a.adc_a_dp(VSPEED)
    a.mov_dpx_a(VPH)
    a.bpl('ch_up')
    a.eor_a_imm(0xFF)
    a.label('ch_up')
    a.asl_a()                            # triangle 0..254
    a.mov_y_a()
    a.mov_a_dpx(VAMP)
    a.asl_a()
    a.bcc('ch_v2')
    a.mov_a_imm(0xFF)
    a.label('ch_v2')
    a.mul()                              # Y = 0 .. 2 * amp
    a.mov_a_y()
    a.setc()
    a.sbc_a_dpx(VAMP)
    a.mov_dp_a(TL)
    a.mov_a_imm(0)
    a.sbc_a_imm(0)
    a.mov_dp_a(TL + 1)
    a.mov_a_dpx(PL)
    a.mov_y_dpx(PH)
    a.addw(TL)
    a.dsp_v(0x02)
    a.mov_a_y()
    a.dsp_v(0x03)
    a.ret()

    # read the channel's events until a note, rest or tie
    a.label('fetch')
    a.mov_a_dpx(PTRL)
    a.mov_dp_a(CP)
    a.mov_a_dpx(PTRH)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.label('f_next')
    a.mov_a_ind_y(CP)
    a.inc_y()
    a.cmp_a_imm(0)
    a.bne('f_1')
    a.jmp('f_end')
    a.label('f_1')
    a.bmi('f_2')
    a.mov_dpx_a(LEN)                     # $01-$7F length
    a.bra('f_next')
    a.label('f_2')
    a.cmp_a_imm(0xDC)
    a.bcs_far('f_3')
    # note
    a.push_y()
    a.call('notepitch')
    a.pop_y()
    a.mov_a_dpx(LEN)
    a.mov_dpx_a(DUR)
    a.mov_a_dpx(ADSR1)
    a.dsp_v(0x05)
    a.mov_a_dpx(ADSR2)
    a.dsp_v(0x06)
    a.mov_a_dpx(PL)
    a.dsp_v(0x02)
    a.mov_a_dpx(PH)
    a.dsp_v(0x03)
    a.mov_a_imm(1)
    a.mov_dpx_a(KEYED)
    a.mov_a_imm(64)
    a.mov_dpx_a(VPH)
    a.mov_a_imm(VIB_DELAY)
    a.mov_dpx_a(VDLY)
    a.mov_a_dp(KONACC)
    a.or_a_absx('konbit')
    a.mov_dp_a(KONACC)
    a.jmp('f_done')
    a.label('f_3')
    a.bne('f_4')
    a.mov_a_dpx(LEN)                     # $DC tie
    a.mov_dpx_a(DUR)
    a.jmp('f_done')
    a.label('f_4')
    a.cmp_a_imm(0xDD)
    a.bne('f_5')
    a.mov_a_dpx(LEN)                     # $DD rest
    a.mov_dpx_a(DUR)
    a.call('release')
    a.jmp('f_done')
    a.label('f_5')
    a.cmp_a_imm(0xE0)
    a.bne('f_6')
    a.mov_a_ind_y(CP)                    # $E0 L
    a.inc_y()
    a.mov_dpx_a(LEN)
    a.jmp('f_next')
    a.label('f_6')
    a.cmp_a_imm(0xE1)
    a.bne('f_7')
    a.mov_a_ind_y(CP)                    # $E1 instrument
    a.inc_y()
    a.mov_dp_y(TMP)
    a.asl_a()
    a.asl_a()
    a.asl_a()
    a.mov_y_a()
    a.mov_a_absy('insttab')
    a.dsp_v(0x04)
    a.mov_a_absy('insttab', 1)
    a.mov_dpx_a(ADSR1)
    a.mov_a_absy('insttab', 2)
    a.mov_dpx_a(ADSR2)
    a.mov_a_absy('insttab', 3)
    a.mov_dpx_a(REL)
    a.mov_a_absy('insttab', 4)
    a.mov_dpx_a(TRANS)
    a.mov_a_absy('insttab', 5)
    a.mov_dpx_a(TUNE)
    a.mov_y_dp(TMP)
    a.jmp('f_next')
    a.label('f_7')
    a.cmp_a_imm(0xE2)
    a.bne('f_8')
    a.mov_a_ind_y(CP)                    # $E2 volume
    a.inc_y()
    a.mov_dpx_a(VOLL)
    a.mov_a_ind_y(CP)
    a.inc_y()
    a.mov_dpx_a(VOLR)
    a.mov_dp_y(TMP)
    a.call('setvol')
    a.mov_y_dp(TMP)
    a.jmp('f_next')
    a.label('f_8')
    a.cmp_a_imm(0xE3)
    a.bne('f_9')
    a.mov_a_ind_y(CP)                    # $E3 gate
    a.inc_y()
    a.mov_dpx_a(GATE)
    a.jmp('f_next')
    a.label('f_9')
    a.cmp_a_imm(0xE4)
    a.bne('f_10')
    a.mov_a_ind_y(CP)                    # $E4 vibrato
    a.inc_y()
    a.mov_dpx_a(VDEP)
    a.jmp('f_next')
    a.label('f_10')
    a.cmp_a_imm(0xE5)
    a.bne('f_11')
    a.label('f_jump')                    # $E5 lo hi
    a.mov_a_ind_y(CP)
    a.push_a()
    a.inc_y()
    a.mov_a_ind_y(CP)
    a.mov_dp_a(CP + 1)
    a.pop_a()
    a.mov_dp_a(CP)
    a.mov_y_imm(0)
    a.jmp('f_next')
    a.label('f_11')
    a.cmp_a_imm(0xE7)
    a.bne('f_12')
    a.mov_a_y()                          # $E7 call: return address = CP + Y + 2
    a.clrc()
    a.adc_a_imm(2)
    a.clrc()
    a.adc_a_dp(CP)
    a.mov_absx_a(RETL)
    a.mov_a_dp(CP + 1)
    a.adc_a_imm(0)
    a.mov_absx_a(RETH)
    a.jmp('f_jump')
    a.label('f_12')
    a.cmp_a_imm(0xE8)
    a.bne('f_13')
    a.mov_a_absx(RETL)                   # $E8 return
    a.mov_dp_a(CP)
    a.mov_a_absx(RETH)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.jmp('f_next')
    a.label('f_13')
    a.cmp_a_imm(0xE9)
    a.bne('f_14')
    a.mov_a_ind_y(CP)                    # $E9 n: repeat start
    a.inc_y()
    a.mov_dpx_a(REPC)
    a.mov_a_y()
    a.clrc()
    a.adc_a_dp(CP)
    a.mov_absx_a(REPL)
    a.mov_a_dp(CP + 1)
    a.adc_a_imm(0)
    a.mov_absx_a(REPH)
    a.jmp('f_next')
    a.label('f_14')
    a.cmp_a_imm(0xEA)
    a.bne('f_15')
    a.dec_dpx(REPC)                      # $EA repeat end
    a.bne('f_rep')
    a.jmp('f_next')
    a.label('f_rep')
    a.mov_a_absx(REPL)
    a.mov_dp_a(CP)
    a.mov_a_absx(REPH)
    a.mov_dp_a(CP + 1)
    a.mov_y_imm(0)
    a.jmp('f_next')
    a.label('f_15')
    a.cmp_a_imm(0xEB)
    a.bne('f_end')
    a.mov_a_ind_y(CP)                    # $EB d n: bend
    a.inc_y()
    a.mov_dpx_a(BD)
    a.mov_a_ind_y(CP)
    a.inc_y()
    a.mov_dpx_a(BN)
    a.jmp('f_next')
    a.label('f_end')                     # $00 / $E6 / unknown: the channel stops
    a.mov_a_imm(0)
    a.mov_dpx_a(ON)
    a.call('release')
    a.label('f_done')
    a.mov_a_y()
    a.clrc()
    a.adc_a_dp(CP)
    a.mov_dpx_a(PTRL)
    a.mov_a_dp(CP + 1)
    a.adc_a_imm(0)
    a.mov_dpx_a(PTRH)
    a.ret()

    # A = note byte ($80-$DB): PL/PH, VAMP, bend (clobbers Y, TL, TMP)
    a.label('notepitch')
    a.and_a_imm(0x7F)
    a.clrc()
    a.adc_a_dpx(TRANS)
    a.mov_y_a()
    a.mov_a_absy('ptl')
    a.mov_dpx_a(PL)
    a.mov_a_absy('pth')
    a.mov_dpx_a(PH)
    a.mov_a_dpx(TUNE)                    # P += (PH * T + (PL * T >> 8)) >> 2
    a.beq('np_tuned')
    a.mov_y_dpx(PL)
    a.mul()
    a.mov_dp_y(TMP)
    a.mov_a_dpx(TUNE)
    a.mov_y_dpx(PH)
    a.mul()
    a.mov_dp_a(TL)
    a.mov_dp_y(TL + 1)
    a.mov_a_dp(TMP)
    a.clrc()
    a.adc_a_dp(TL)
    a.mov_dp_a(TL)
    a.mov_a_imm(0)
    a.adc_a_dp(TL + 1)
    a.mov_dp_a(TL + 1)
    a.lsr_dp(TL + 1)
    a.ror_dp(TL)
    a.lsr_dp(TL + 1)
    a.ror_dp(TL)
    a.mov_a_dpx(PL)
    a.mov_y_dpx(PH)
    a.addw(TL)
    a.mov_dpx_a(PL)
    a.mov_dpx_y(PH)
    a.label('np_tuned')
    # vibrato amplitude = PH * VDEP >> 4
    a.mov_a_dpx(VDEP)
    a.mov_y_dpx(PH)
    a.mul()
    a.mov_dp_a(TL)
    a.mov_a_y()
    a.call('shr4')
    a.mov_dpx_a(VAMP)
    # bend
    a.mov_a_dpx(BN)
    a.and_a_imm(0x7F)
    a.mov_dpx_a(BCNT)
    a.bne('np_bend')
    a.ret()
    a.label('np_bend')
    a.mov_a_dpx(BD)                      # |d| * PH >> 4, signed
    a.bpl('np_pos')
    a.eor_a_imm(0xFF)
    a.clrc()
    a.adc_a_imm(1)
    a.label('np_pos')
    a.mov_y_dpx(PH)
    a.mul()
    a.mov_dp_a(TL)
    a.mov_dp_y(TL + 1)
    for _ in range(4):
        a.lsr_dp(TL + 1)
        a.ror_dp(TL)
    a.mov_a_dpx(BD)
    a.bpl('np_store')
    a.mov_a_dp(TL)                       # negate
    a.eor_a_imm(0xFF)
    a.clrc()
    a.adc_a_imm(1)
    a.mov_dp_a(TL)
    a.mov_a_dp(TL + 1)
    a.eor_a_imm(0xFF)
    a.adc_a_imm(0)
    a.mov_dp_a(TL + 1)
    a.label('np_store')
    a.mov_a_dp(TL)
    a.mov_dpx_a(BSL)
    a.mov_a_dp(TL + 1)
    a.mov_dpx_a(BSH)
    a.mov_a_dpx(BN)
    a.bmi('np_arrive')
    a.ret()
    a.label('np_arrive')                 # start BCNT steps away: P -= step * BCNT
    a.mov_a_dpx(BCNT)
    a.mov_dp_a(TMP)
    a.label('np_al')
    a.mov_a_dpx(PL)
    a.mov_y_dpx(PH)
    a.subw(TL)
    a.mov_dpx_a(PL)
    a.mov_a_y()
    a.and_a_imm(0x3F)
    a.mov_dpx_a(PH)
    a.dec_dp(TMP)
    a.bne('np_al')
    a.ret()
    # (TL, A) = 16-bit value lo/hi -> A = min(255, value >> 4)
    a.label('shr4')
    a.mov_dp_a(TL + 1)
    for _ in range(4):
        a.lsr_dp(TL + 1)
        a.ror_dp(TL)
    a.mov_a_dp(TL + 1)
    a.beq('s4_ok')
    a.mov_a_imm(0xFF)
    a.ret()
    a.label('s4_ok')
    a.mov_a_dp(TL)
    a.ret()

    # ------------------------------------------------------------ tables
    a.label('vbit')
    a.data([1, 2])
    a.label('konbit')
    a.data([1 << (c + 2) for c in range(NCH)])
    a.label('ptl')
    a.data([p & 0xFF for p in music.PTAB])
    a.label('pth')
    a.data([p >> 8 for p in music.PTAB])
    for name in ('amb_level', 'amb_gap', 'amb_src', 'amb_pitch', 'amb_vol', 'amb_pan'):
        a.label(name)
        if name == 'amb_pitch':
            for p in amb_tables[name]:
                a.data([p & 0xFF, p >> 8])
        else:
            a.data(amb_tables[name])
    return a
